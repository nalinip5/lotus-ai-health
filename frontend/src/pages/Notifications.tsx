import { useState } from "react";
import { act, time, useApi } from "../api";

export default function Notifications() {
  const { data } = useApi<any>("/notifications");
  const [sel, setSel] = useState<any>(null);
  const items: any[] = data?.items ?? [];
  const open = (n: any) => {
    setSel(n);
    if (!n.read) act("/notifications/read", { id: n.id });
  };
  return (
    <>
      <div className="pagehead">
        <div>
          <h1>Notification center</h1>
          <p className="sub">Email notifications generated by live workflow events. Synthetic recipients — nothing is actually sent.</p>
        </div>
        <button className="sm" onClick={() => act("/notifications/read", {}, "All marked read")}>Mark all read</button>
      </div>
      <div className="grid-2">
        <section className="card flush">
          {items.map((n) => (
            <button key={n.id} className={`mail ${n.read ? "" : "unread"} ${sel?.id === n.id ? "on" : ""}`} onClick={() => open(n)}>
              <div className="mail-top"><span>{n.subject}</span><span className="mono dim">{time(n.at)}</span></div>
              <div className="dim">to {n.to}</div>
            </button>
          ))}
          {items.length === 0 && <div className="empty">No notifications yet.</div>}
        </section>
        <div className="stack">
          <section className="card">
            <h2>Email preview</h2>
            {!sel ? <div className="empty sm">Select a notification to read it.</div> : (
              <div className="mailview">
                <div className="kv"><span>To</span><span className="mono">{sel.to}</span></div>
                <div className="kv"><span>Subject</span><b>{sel.subject}</b></div>
                <p>{sel.body}</p>
                {sel.case_id && <a href={`#/case/${sel.case_id}/summary`}>Open {sel.case_id} →</a>}
              </div>
            )}
          </section>
          <section className="card">
            <h2>Email settings</h2>
            {(data?.settings ?? []).map((s: any) => (
              <label key={s.category} className="toggle">
                <input type="checkbox" checked={s.enabled}
                  onChange={(e) => act("/notifications/settings", { category: s.category, enabled: e.target.checked })} />
                <div><b>{s.label}</b><div className="dim mono">to {s.to}</div></div>
              </label>
            ))}
            <p className="note">Turning a category off stops those emails from being generated.</p>
          </section>
        </div>
      </div>
    </>
  );
}
